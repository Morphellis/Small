/*
 * Блок «Как поднять тревожность»: логика подсчёта, чтобы человек понимал, а не заучивал раскладку.
 */
import type { LuscherDef } from "../types";
import { swatches as sws } from "./common";

export function guideHtml(def: LuscherDef): string {
  return `
    <summary><b>Расчёт показателя тревожности</b></summary>
    <div class="lu-guide-body">
      <p>Показатель тревожности составляет от 0 до 12 баллов и зависит от позиций цветов в восьмицветовом ряду. Баллы обозначаются знаками «!»:</p>
      <ul>
        <li><b>Основные цвета</b> ${sws([1, 2, 3, 4])} (синий, зелёный, красный, жёлтый) добавляют баллы при расположении в конце ряда:
          6-е место <b>+1</b>, 7-е <b>+2</b>, 8-е <b>+3</b>.</li>
        <li><b>Дополнительные цвета</b> ${sws([7, 0, 6])} (чёрный, серый, коричневый) добавляют баллы при расположении в начале ряда:
          1-е место <b>+3</b>, 2-е <b>+2</b>, 3-е <b>+1</b>.</li>
        <li><b>Фиолетовый</b> ${sws([5])} не влияет на показатель тревожности. В эталонном ряду он занимает 5-е место.</li>
      </ul>
      <p><b>Максимум — 12 баллов:</b> три дополнительных цвета занимают первые три места (3 + 2 + 1),
        три основных — последние три места (1 + 2 + 3). Четвёртый основной цвет и фиолетовый находятся в середине.
        При расположении основных цветов в начале, а дополнительных в конце показатель снижается.</p>
      <p>Порядок цветов внутри этих групп не меняет сумму баллов тревожности. В режиме эталонных ответов используется ряд
        ${sws([7, 0, 6, 1, 5, 2, 4, 3])}, обратный аутогенной норме ${sws([3, 4, 2, 5, 1, 6, 0, 7])}.
        Для него также максимальны отклонение от нормы (32) и показатель усталости по вегетативному коэффициенту.</p>
      <p>Итоговый показатель определяется <b>по второму выбору</b>. Первый выбор сохраняется в протоколе для сравнения.</p>${def.variant === "full" ? `
      <p><b>В полном тесте</b> после пяти предпочтительных цветов выбираются <b>неприятные</b>.
        Первый из них занимает 8-е место, второй — 7-е, оставшийся цвет — 6-е.
        Для эталонного ряда сначала выбирается красный ${sws([3])}, затем жёлтый ${sws([4])}; зелёный занимает 6-е место.
        Ахроматические цвета, таблицы пар и фигуры не влияют на показатель тревожности.</p>` : ""}
    </div>`;
}
