/*
 * Блок «Как поднять тревожность»: логика подсчёта, чтобы человек понимал, а не заучивал раскладку.
 */
import type { LuscherDef } from "../types";
import { swatches as sws } from "./common";

export function guideHtml(def: LuscherDef): string {
  return `
    <summary>Как поднять тревожность</summary>
    <div class="lu-guide-body">
      <p>Тревожность (от 0 до 12) считается по ряду из восьми цветов. Баллы дают цвета, которые стоят не на своём месте.</p>
      <ul>
        <li>Основные ${sws([1, 2, 3, 4])}: синий, зелёный, красный, жёлтый. В конце ряда дают тревогу: 6-е место +1, 7-е +2, 8-е +3.</li>
        <li>Тёмные ${sws([7, 0, 6])}: чёрный, серый, коричневый. В начале ряда: 1-е место +3, 2-е +2, 3-е +1.</li>
        <li>Фиолетовый ${sws([5])} не влияет. Его место в середине, 4-е или 5-е.</li>
      </ul>
      <p>Максимум 12: три тёмных в начало, три основных в конец, четвёртый основной и фиолетовый посередине. Чтобы снизить тревожность, наоборот.</p>
      <p>Ключ берёт порядок ${sws([7, 0, 6, 1, 5, 2, 4, 3])}. Это норма спокойного человека ${sws([3, 4, 2, 5, 1, 6, 0, 7])}, только задом наперёд,
        поэтому отклонение от нормы (32) и усталость по вегетативному коэффициенту тоже выходят наибольшими.</p>
      <p>Итог считается по второму выбору. Первый лучше сделать таким же: два разных ряда выглядят непоследовательно.</p>${def.variant === "full" ? `
      <p>В полном тесте после пяти симпатичных цветов спрашивают неприятные. Самый неприятный встаёт на 8-е место, следующий на 7-е.
        Первым неприятным выбирайте красный ${sws([3])}, вторым жёлтый ${sws([4])}, тогда зелёный окажется 6-м.
        Ахроматические цвета, пары и фигуры на тревожность не влияют.</p>` : ""}
    </div>`;
}
