/*
 * Контракт между оболочкой сайта и тестами.
 *
 * Оболочка (src/app) знает только список тестов и умеет показать один из них. Как тест выглядит и как
 * считается, решает сам тест: опросники вроде СМОЛ и СМИЛ собраны на общем движке (src/kinds/questionnaire),
 * а тест с другой механикой (например, цветовой тест Люшера) может целиком нарисовать свой экран.
 */

/** Запись в реестре тестов: всё, что нужно для переключателя, без загрузки самого теста. */
export interface TestEntry {
  /** Идентификатор: часть адреса (#smil) и префикс ключей в localStorage. */
  id: string;
  /** Короткое название на переключателе: «СМИЛ». */
  title: string;
  /** Подпись под названием: «566 утверждений». */
  subtitle: string;
  /** Всплывающая подсказка на переключателе: «Л. Н. Собчик». */
  hint: string;
  /** Загрузка теста по требованию: каждый тест попадает в свой файл сборки. */
  load: () => Promise<TestModule>;
}

/** Что оболочка передаёт тесту при показе. */
export interface AppContext {
  /** Все тесты — для переключателя. */
  tests: readonly TestEntry[];
  /** Какой тест сейчас открыт. */
  currentId: string;
  /** Перейти на другой тест. */
  switchTo(id: string): void;
}

/** Функция, которая убирает тест со страницы: снимает обработчики, таймеры, наблюдателей. */
export type Unmount = () => void;

/** Загруженный тест. */
export interface TestModule {
  /** Нарисовать тест внутри root. Вернуть функцию, которая всё уберёт. */
  mount(root: HTMLElement, ctx: AppContext): Unmount;
}
